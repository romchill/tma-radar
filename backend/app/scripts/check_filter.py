def verdict(text: str) -> tuple[bool, str]:
    for pattern, rx in STOPS:
        if rx.search(text):
            return False, "стоп: " + pattern[:38]
    hits = [p for p, rx in KEYWORDS if rx.search(text)]
    return bool(hits), (hits[0][:38] if hits else "нет совпадений")


def main() -> int:
    wrong = 0
    print(f"ключевиков {len(KEYWORDS)}, стоп-слов {len(STOPS)}\n")

    for expected in (False, True):
        print("=== должны отсеяться ===" if not expected else "\n=== должны пройти ===")
        for want, text, source in CASES:
            if want != expected:
                continue
            passed, why = verdict(text)
            ok = passed == want
            wrong += not ok
            mark = "ok  " if ok else "FAIL"
            print(f"  {mark} {source:<20} {why:<42} {text[:46]}")

    print()
    if wrong:
        print(f"ПРОВАЛОВ: {wrong} из {len(CASES)}")
    else:
        print(f"всё верно: {len(CASES)}/{len(CASES)}")
    return 1 if wrong else 0


if __name__ == "__main__":
    sys.exit(main())
