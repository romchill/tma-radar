"""Сигнал «пришли новые сообщения» между сборщиками и скорером.

Скорер раньше просыпался каждые 5 секунд и спрашивал базу, нет ли работы.
На своём Postgres это ничего не стоило, но на бесплатном хостинге база
считает время работы: она засыпает после 5 минут покоя, а запрос раз в
5 секунд не давал ей заснуть никогда — месячного лимита хватило бы дней на
шестнадцать.

Теперь сборщики будят скорера сами, сразу после того как сохранят улов.
Между циклами никто базу не трогает, она спит, и лид при этом оценивается
не позже, а раньше: ждать общего интервала больше не нужно.

Задачи живут в одном процессе, поэтому хватает обычного asyncio.Event.
"""

from __future__ import annotations

import asyncio

_new_messages = asyncio.Event()
_cycle_done = asyncio.Event()


async def _wait(event: asyncio.Event, timeout: float) -> bool:
    """True — разбудили сигналом, False — вышло время.

    Ожидание по времени остаётся страховкой: если работа попала в очередь
    мимо сигнала (например, осталась с прошлого запуска), её всё равно
    разберут, просто позже.
    """
    try:
        await asyncio.wait_for(event.wait(), timeout=timeout)
        return True
    except asyncio.TimeoutError:
        return False
    finally:
        event.clear()


def ping() -> None:
    """Сборщик сохранил новые сообщения — разбудить скорера."""
    _new_messages.set()


async def wait(timeout: float) -> bool:
    """Скорер ждёт улова."""
    return await _wait(_new_messages, timeout)


def cycle_done() -> None:
    """Скорер разобрал очередь — можно делать всё остальное по базе."""
    _cycle_done.set()


async def wait_cycle(timeout: float) -> bool:
    """Напоминалка ждёт конца цикла, чтобы сходить в базу заодно со всеми.

    Она проверяет сроки по часам, а не по событиям, и раньше дёргала базу
    сама по себе каждые 5 минут. На бесплатном хостинге любой лишний заход
    держит базу включённой ещё 5 минут, поэтому дешевле присоединиться к уже
    открытому окну, чем открывать своё.
    """
    return await _wait(_cycle_done, timeout)
